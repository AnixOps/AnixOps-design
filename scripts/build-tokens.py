#!/usr/bin/env python3
"""Generate every platform output from tokens/tokens.json.

Dependency free. Run from the repository root:

    python3 scripts/build-tokens.py           # write all outputs
    python3 scripts/build-tokens.py --check   # exit 1 if any output is stale

Outputs:

    tokens/css/tokens.css                  CSS custom properties (light, dark, system)
    tokens/tailwind/preset.cjs             Tailwind CSS v3 preset
    tokens/tailwind/theme.css              Tailwind CSS v4 @theme
    tokens/element-plus/element-plus.css   Element Plus variable overrides
    tokens/flutter/anixops_tokens.dart     Flutter ThemeData, ColorScheme and extension
    tokens/go/anixops/tokens.go            Go: UI colours and terminal palette
    tokens/rust/anixops_tokens.rs          Rust (egui, ratatui): dependency-free constants

CSS theme pattern: bare :root holds light values; dark values apply under
prefers-color-scheme: dark unless data-theme="light" is set, and always under
data-theme="dark".
"""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "tokens" / "tokens.json"
ASCII_MARK = ROOT / "brand" / "assets" / "ascii-mark.txt"
VERSION = "1.0.2"
HEADER = f"Generated by scripts/build-tokens.py from tokens/tokens.json. Do not edit. AnixOps Design {VERSION}."

DARK_MEDIA = '@media (prefers-color-scheme: dark)'
DARK_AUTO = ':root:not([data-theme="light"])'
DARK_FORCED = ':root[data-theme="dark"]'


# ---------------------------------------------------------------- helpers

def leaves(node, path=()):
    """Yield (path, value) for every token below node."""
    for key, child in node.items():
        if key.startswith("$"):
            continue
        if isinstance(child, dict) and "$value" in child:
            yield path + (key,), child["$value"]
        elif isinstance(child, dict):
            yield from leaves(child, path + (key,))


def values(group):
    """Ordered {name: value} for one flat token group."""
    return {k: v["$value"] for k, v in group.items() if not k.startswith("$")}


def rgba(value):
    """Parse #RRGGBB or rgba(r, g, b, a) into (r, g, b, a) with a in 0..1."""
    if value.startswith("#"):
        h = value[1:]
        return int(h[0:2], 16), int(h[2:4], 16), int(h[4:6], 16), 1.0
    m = re.fullmatch(r"rgba\(\s*(\d+),\s*(\d+),\s*(\d+),\s*([\d.]+)\s*\)", value)
    if not m:
        raise ValueError(f"unsupported colour {value!r}")
    return int(m[1]), int(m[2]), int(m[3]), float(m[4])


def mix(a, b, weight):
    """Mix hex colour a into hex colour b; weight is the share of b (0..1)."""
    ca, cb = rgba(a), rgba(b)
    return "#" + "".join(f"{round(ca[i] * (1 - weight) + cb[i] * weight):02X}" for i in range(3))


def camel(name):
    head, *rest = re.split(r"[-.]", name)
    return head + "".join(p[:1].upper() + p[1:] for p in rest)


def go_name(prefix, name):
    c = camel(name)
    return prefix + c[:1].upper() + c[1:]


def const_case(name):
    return re.sub(r"[-.]", "_", name).upper()


def px(value):
    return float(value.removesuffix("px"))


def num(value):
    return f"{value:g}"


def css_value(value):
    if isinstance(value, list) and value and all(isinstance(v, (int, float)) for v in value):
        return "cubic-bezier(" + ", ".join(f"{v:g}" for v in value) + ")"
    if isinstance(value, list):
        return ", ".join(f'"{v}"' if " " in v else v for v in value)
    return str(value)


def block(selector, decls, indent=""):
    inner = "\n".join(f"{indent}  {name}: {value};" for name, value in decls)
    return f"{indent}{selector} {{\n{inner}\n{indent}}}"


def themed_css(light, dark, extra_dark=()):
    """Light on :root, dark under the media query and the forced attribute."""
    dark = list(dark) + list(extra_dark)
    return "\n\n".join([
        block(":root", light),
        f"{DARK_MEDIA} {{\n" + block(DARK_AUTO, dark, "  ") + "\n}",
        block(DARK_FORCED, dark),
    ])


# ---------------------------------------------------------------- CSS

def build_css(t):
    common, light, dark, comments = [], [], [], []
    for path, value in leaves(t):
        group = path[0]
        if group == "terminal":
            continue
        if group == "color" and path[1] in ("light", "dark"):
            target = light if path[1] == "light" else dark
            target.append((f"--{'-'.join(path[2:])}", css_value(value)))
        elif group == "color":  # brand
            common.append((f"--brand-{'-'.join(path[2:])}", css_value(value)))
        elif group == "type":
            name = path[1]
            common.append((f"--type-{name}-size", value["fontSize"]))
            common.append((f"--type-{name}-line", f"{value['lineHeight']:g}"))
            common.append((f"--type-{name}-weight", str(value["fontWeight"])))
            common.append((f"--type-{name}-tracking", value["letterSpacing"]))
        elif group == "breakpoint":
            comments.append(f"{path[1]} {value}")
        elif group == "font":
            common.append((f"--font-{path[2]}" if path[1] == "family" else f"--weight-{path[2]}", css_value(value)))
        elif group == "motion":
            common.append((f"--{'ease' if path[1] == 'easing' else 'dur'}-{path[2]}", css_value(value)))
        else:
            common.append((f"--{'-'.join(path)}", css_value(value)))
    common.append(("--brand-gradient", "linear-gradient(135deg, var(--brand-gradient-start), var(--brand-gradient-end))"))
    return "\n".join([
        f"/* {HEADER} */",
        f"/* Breakpoints (use literally in media queries): {', '.join(comments)} */",
        "",
        themed_css(common + light + [("color-scheme", "light")], dark, [("color-scheme", "dark")]),
        "",
        "@media (max-width: 833px) {\n  :root {\n    --type-display-size: 34px;\n    --type-title-1-size: 28px;\n  }\n}",
        "",
    ])


# ---------------------------------------------------------------- Tailwind

def js(value, indent=0):
    """Small JSON-like JS literal writer with stable, readable output."""
    pad = "  " * indent
    if isinstance(value, dict):
        if not value:
            return "{}"
        items = []
        for k, v in value.items():
            key = k if re.fullmatch(r"[A-Za-z_$][\w$]*", k) else json.dumps(k)
            items.append(f"{pad}  {key}: {js(v, indent + 1)},")
        return "{\n" + "\n".join(items) + f"\n{pad}}}"
    if isinstance(value, list):
        return "[" + ", ".join(js(v, indent) for v in value) + "]"
    return json.dumps(value)


def build_tailwind_v3(t):
    c = t["color"]
    colors = {f"brand-{k}": f"var(--brand-{k})" for k in values(c["brand"])}
    colors.update({k: f"var(--{k})" for k in values(c["light"])})
    font_size = {
        name: [f"var(--type-{name}-size)", {
            "lineHeight": f"var(--type-{name}-line)",
            "letterSpacing": f"var(--type-{name}-tracking)",
            "fontWeight": f"var(--type-{name}-weight)",
        }]
        for name in values(t["type"])
    }
    theme = {
        "screens": values(t["breakpoint"]),
        "extend": {
            "colors": colors,
            "backgroundImage": {"brand-gradient": "var(--brand-gradient)"},
            "fontFamily": {"sans": ["var(--font-sans)"], "mono": ["var(--font-mono)"]},
            "fontSize": font_size,
            "borderRadius": {k: f"var(--radius-{k})" for k in values(t["radius"])},
            "boxShadow": {k: f"var(--shadow-{k})" for k in values(t["shadow"])},
            "maxWidth": {k: f"var(--size-{k})" for k in values(t["size"]) if k.startswith("content-")},
            "height": {k: f"var(--size-{k})" for k in values(t["size"]) if k.startswith("control-")},
            "transitionTimingFunction": {k: f"var(--ease-{k})" for k in values(t["motion"]["easing"])},
            "transitionDuration": {k: f"var(--dur-{k})" for k in values(t["motion"]["duration"])},
            "zIndex": {k: f"var(--z-{k})" for k in values(t["z"])},
        },
    }
    return "\n".join([
        f"// {HEADER}",
        "// Tailwind CSS v3 preset. Load tokens/css/tokens.css first; every value is a",
        "// CSS variable, so light and dark switch without `dark:` variants.",
        "// Spacing is not overridden: Tailwind's default scale already matches --space-*.",
        "/** @type {import('tailwindcss').Config} */",
        f"module.exports = {js({'theme': theme})};",
        "",
    ])


def build_tailwind_v4(t):
    c = t["color"]
    color_lines = [f"  --color-brand-{k}: var(--brand-{k});" for k in values(c["brand"])]
    color_lines += [f"  --color-{k}: var(--{k});" for k in values(c["light"])]
    other = []
    for name in values(t["type"]):
        other += [
            f"  --text-{name}: var(--type-{name}-size);",
            f"  --text-{name}--line-height: var(--type-{name}-line);",
            f"  --text-{name}--letter-spacing: var(--type-{name}-tracking);",
            f"  --text-{name}--font-weight: var(--type-{name}-weight);",
        ]
    other += [f"  --container-{k}: var(--size-{k});" for k in values(t["size"]) if k.startswith("content-")]
    # Theme names that tokens.css also defines (--font-*, --radius-*, --shadow-*, --ease-*)
    # get the literal token values: `--x: var(--x)` would be a cycle, and identical values
    # make load order irrelevant.
    literal = [f"  --font-{k}: {css_value(v)};" for k, v in values(t["font"]["family"]).items()]
    literal += [f"  --shadow-{k}: {v};" for k, v in values(t["shadow"]).items()]
    literal += [f"  --ease-{k}: {css_value(v)};" for k, v in values(t["motion"]["easing"]).items()]
    literal += [f"  --radius-{k}: {v};" for k, v in values(t["radius"]).items()]
    literal += [f"  --breakpoint-{k}: {v};" for k, v in values(t["breakpoint"]).items()]
    return "\n".join([
        f"/* {HEADER} */",
        "/* Tailwind CSS v4. Usage:",
        '     @import "tailwindcss";',
        '     @import "<path>/tokens/css/tokens.css";',
        '     @import "<path>/tokens/tailwind/theme.css";',
        "   Colours are CSS variables, so light and dark switch without `dark:` variants. */",
        "",
        "@theme {",
        "  --breakpoint-*: initial;",
        *literal,
        "}",
        "",
        "@theme inline {",
        *color_lines,
        *other,
        "}",
        "",
        "/* v4 has no theme namespace for these; plain utilities instead. */",
        "@utility bg-brand-gradient {\n  background-image: var(--brand-gradient);\n}",
        *[f"@utility duration-{k} {{\n  transition-duration: var(--dur-{k});\n}}" for k in values(t["motion"]["duration"])],
        *[f"@utility z-{k} {{\n  z-index: var(--z-{k});\n}}" for k in values(t["z"])],
        "",
    ])


