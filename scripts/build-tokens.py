def build_element_plus(t):
    c = t["color"]

    def theme_decls(theme):
        p = values(c[theme])
        base = "#FFFFFF" if theme == "light" else p["bg-elevated"]
        shade = "#000000" if theme == "light" else "#FFFFFF"
        decls = []
        roles = [("primary", p["accent-fill"]), ("success", p["success"]), ("warning", p["warning"]),
                 ("danger", p["danger"]), ("error", p["danger"]), ("info", p["label-2"])]
        for role, colour in roles:
            decls.append((f"--el-color-{role}", colour))
            for step in (3, 5, 7, 8, 9):
                decls.append((f"--el-color-{role}-light-{step}", mix(colour, base, step / 10)))
            decls.append((f"--el-color-{role}-dark-2", mix(colour, shade, 0.2)))
        return decls

    shared = [
        ("--el-bg-color", "var(--bg-elevated)"),
        ("--el-bg-color-page", "var(--bg)"),
        ("--el-bg-color-overlay", "var(--bg-elevated)"),
        ("--el-text-color-primary", "var(--label-1)"),
        ("--el-text-color-regular", "var(--label-1)"),
        ("--el-text-color-secondary", "var(--label-2)"),
        ("--el-text-color-placeholder", "var(--label-3)"),
        ("--el-text-color-disabled", "var(--label-3)"),
        ("--el-border-color", "var(--separator-strong)"),
        ("--el-border-color-light", "var(--separator)"),
        ("--el-border-color-lighter", "var(--separator)"),
        ("--el-border-color-extra-light", "var(--separator)"),
        ("--el-border-color-dark", "var(--separator-strong)"),
        ("--el-border-color-darker", "var(--separator-strong)"),
        ("--el-fill-color", "var(--fill-1)"),
        ("--el-fill-color-light", "var(--fill-1)"),
        ("--el-fill-color-lighter", "var(--fill-1)"),
        ("--el-fill-color-extra-light", "var(--fill-1)"),
        ("--el-fill-color-dark", "var(--fill-2)"),
        ("--el-fill-color-darker", "var(--fill-3)"),
        ("--el-fill-color-blank", "var(--bg-elevated)"),
        ("--el-box-shadow", "var(--shadow-2)"),
        ("--el-box-shadow-light", "var(--shadow-1)"),
        ("--el-box-shadow-lighter", "var(--shadow-1)"),
        ("--el-box-shadow-dark", "var(--shadow-3)"),
        ("--el-border-radius-base", "var(--radius-xs)"),
        ("--el-border-radius-small", "var(--radius-xs)"),
        ("--el-border-radius-round", "var(--radius-pill)"),
        ("--el-font-family", "var(--font-sans)"),
        ("--el-transition-function-ease-in-out-bezier", "var(--ease-standard)"),
        ("--el-component-size-large", "var(--size-control-lg)"),
        ("--el-component-size", "var(--size-control-md)"),
        ("--el-component-size-small", "var(--size-control-sm)"),
    ]
    return "\n".join([
        f"/* {HEADER} */",
        "/* Element Plus overrides. Load after element-plus/dist/index.css and after",
        "   tokens/css/tokens.css. Do not also load Element Plus's dark CSS or set html.dark:",
        "   these variables follow the system theme and data-theme like tokens.css.",
        "   Primary light-N/dark-2 steps are mixed with the card colour at build time. */",
        "",
        themed_css(shared + theme_decls("light"), theme_decls("dark")),
        "",
    ])


