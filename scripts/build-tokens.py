# ---------------------------------------------------------------- Go

def ascii_mark():
    return ASCII_MARK.read_text(encoding="utf-8").rstrip("\n").split("\n")


def go_aligned(rows):
    rows = list(rows)
    width = max(len(name) for name, _ in rows)
    return [f"\t{name:<{width}} = {rhs}" for name, rhs in rows]


def build_go(t):
    c = t["color"]
    light, dark = values(c["light"]), values(c["dark"])
    out = [
        "// Code generated by scripts/build-tokens.py from tokens/tokens.json. DO NOT EDIT.",
        "",
        "package anixops",
        "",
        "// Version is the AnixOps Design version these tokens come from.",
        f'const Version = "{VERSION}"',
        "",
        "// UI colours. Values are CSS colour strings (#RRGGBB or rgba()).",
        "var (",
    ]
    out += go_aligned((go_name("UI", k), f'Color{{Light: "{light[k]}", Dark: "{dark[k]}"}}') for k in light)
    out += [")", "", "// Brand colours (theme independent).", "const ("]
    out += go_aligned((go_name("Brand", k), f'"{v}"') for k, v in values(c["brand"]).items())
    out += [")", "", "// Terminal palette for CLIs and TUIs.", "var ("]
    out += go_aligned(
        (go_name("Term", k),
         f'TermColor{{Light: "{v["light"]["$value"]}", Dark: "{v["dark"]["$value"]}", '
         f'ANSI256Light: {v["ansi256-light"]["$value"]}, ANSI256Dark: {v["ansi256-dark"]["$value"]}, '
         f'ANSI16: {v["ansi16"]["$value"]}}}')
        for k, v in t["terminal"].items() if not k.startswith("$"))
    out += [")", "", "// ASCIIMark is the three-line ASCII mark used in banners and --version output.",
            "var ASCIIMark = [...]string{"]
    out += [f"\t{json.dumps(line)}," for line in ascii_mark()]
    out += ["}", ""]
    return "\n".join(out)


